MEDDINO_INFLATE = """
# --- ensure inflated 3D checkpoint exists ({ckpt}) ---
export MEDDINOV3_2D_CHECKPOINT="${{RAW_CKPT}}"
export MEDDINOV3_3D_CHECKPOINT="${{SHARED_CKPT_DIR}}/{ckpt}"
if [[ ! -f "${{MEDDINOV3_3D_CHECKPOINT}}" ]]; then
    if [[ ! -f "${{RAW_CKPT}}" ]]; then
        python3 -c "from huggingface_hub import hf_hub_download; import shutil; \\
shutil.copy(hf_hub_download(repo_id='ricklisz123/MedDINOv3-ViTB-16-CT-3M', filename='model.pth'), '${{RAW_CKPT}}')"
    fi
    python3 "${{REPO}}/nnUNet/nnunetv2/training/nnUNetTrainer/dinov3/{inflate_script}" \\
        --checkpoint "${{RAW_CKPT}}" --d_patch {dpatch} {inflate_extra}--out "${{MEDDINOV3_3D_CHECKPOINT}}"
fi
"""


def _short(eid: str) -> str:
    return eid.replace("meddinov3_", "m_")[:24]


def build_script(exp: dict, registry: dict) -> str:
    if not exp.get("implemented"):
        raise ValueError(f"{exp['id']}: not implemented (requires {exp.get('requires')}); "
                         f"cannot generate a runnable script yet.")
    fold = exp.get("folds", [0])[0]
    env = resolve_env(exp)
    parts = [HEADER.format(eid=exp["id"], name=exp["name"],
                           rationale=exp.get("expected_rationale", ""), short=_short(exp["id"]))]

    if exp.get("model_family") == "meddinov3":
        ckpt = inflated_checkpoint_name(exp)
        dpatch = env.get("MEDDINOV3_D_PATCH", "8")
        is_ashwin = "ashwin" in (exp.get("trainer") or "")
        parts.append(MEDDINO_INFLATE.format(
            ckpt=ckpt, dpatch=dpatch,
            inflate_script="inflate_weights_3d_ashwin.py" if is_ashwin else "inflate_weights_3d.py",
            inflate_extra="" if is_ashwin else "--inflation centering ",
        ))

    parts.append("\n# --- experiment env ---")
    parts.extend(env_export_lines({k: v for k, v in env.items()
                                   if k not in ("MEDDINOV3_2D_CHECKPOINT", "MEDDINOV3_3D_CHECKPOINT")}))
    parts.append("")
    parts.append("# --- write run manifest ---")
    parts.append(f'python3 "${{REPO}}/experiments/run_ablation.py" --id {exp["id"]} --dry-run || true')
    parts.append("")
    parts.append("# --- train ---")
    parts.append(compose_train_command(exp, registry, fold))
    parts.append("")
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate SLURM scripts (no submission).")
    ap.add_argument("--id")
    ap.add_argument("--priority", choices=["high", "medium", "low"])
    ap.add_argument("--all-enabled", action="store_true")
    args = ap.parse_args()

    registry = load_registry()
    exps = list_experiments(registry)

    if args.id:
        targets = [get_experiment(args.id, registry)]
    elif args.priority:
        targets = [e for e in exps if e.get("priority") == args.priority and e.get("implemented")]
    elif args.all_enabled:
        targets = [e for e in exps if e.get("enabled") and e.get("implemented")]
    else:
        ap.error("specify --id, --priority, or --all-enabled")

    SLURM_OUT_DIR.mkdir(parents=True, exist_ok=True)
    written, skipped = [], []
    for e in targets:
        if not e.get("implemented"):
            skipped.append(e["id"]); continue
        path = SLURM_OUT_DIR / f"{e['id']}.sh"
        path.write_text(build_script(e, registry))
        path.chmod(0o755)
        written.append(path)

    for p in written:
        print(f"wrote {p}")
    if skipped:
        print(f"skipped (not implemented): {', '.join(skipped)}")
    print(f"\n{len(written)} script(s) generated in {SLURM_OUT_DIR}. Submit with: sbatch <script>")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
