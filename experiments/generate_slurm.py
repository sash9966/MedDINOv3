"""
generate_slurm.py — emit SLURM scripts for selected ablations. Never submits.

    python experiments/generate_slurm.py --id meddinov3_current_d4
    python experiments/generate_slurm.py --priority high
    python experiments/generate_slurm.py --all-enabled

Scripts land in experiments/slurm_generated/<id>.sh and mirror the cluster header
from slurm_meddinov3.sh / CHD_Dataset030_MedDINO_*.sh (bioe partition, modules,
conda, nnUNet paths). For MedDINO experiments the script also ensures the inflated
checkpoint exists (reusing inflate_weights_3d[_ashwin].py) before training — i.e.
it regenerates the proven CHD-script flow from the registry, so the same harness
works on the future cohort by switching dataset_version.
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import (  # noqa: E402
    SLURM_OUT_DIR, compose_train_command, dataset_name, env_export_lines,
    get_experiment, inflated_checkpoint_name, list_experiments, load_registry,
    resolve_env,
)

